void putVarLen(std::vector<uint8_t>& b, uint32_t v)
{
    uint8_t buf[5]; int n = 0;
    do { buf[n++] = uint8_t(v & 0x7F); v >>= 7; } while (v);
    while (n--) b.push_back(uint8_t(buf[n] | (n ? 0x80 : 0)));
}
void putBE32(std::vector<uint8_t>& b, uint32_t v) { b.push_back(uint8_t(v >> 24)); b.push_back(uint8_t(v >> 16)); b.push_back(uint8_t(v >> 8)); b.push_back(uint8_t(v)); }
void putBE16(std::vector<uint8_t>& b, uint16_t v) { b.push_back(uint8_t(v >> 8)); b.push_back(uint8_t(v)); }

bool writeBytes(const std::string& path, const std::vector<uint8_t>& bytes, std::string& error)
{
    std::ofstream f(path, std::ios::binary);
    if (!f) { error = "cannot open for writing: " + path; return false; }
    f.write(reinterpret_cast<const char*>(bytes.data()), std::streamsize(bytes.size()));
    if (!f) { error = "write failed: " + path; return false; }
    return true;
}
bool writeText(const std::string& path, const std::string& text, std::string& error)
{
    std::ofstream f(path, std::ios::binary);
    if (!f) { error = "cannot open for writing: " + path; return false; }
    f << text;
    if (!f) { error = "write failed: " + path; return false; }
    return true;
}
std::string jsonEscape(const std::string& s)
{
    std::string o; for (char c : s) { if (c == '"' || c == '\\') { o += '\\'; o += c; } else if ((unsigned char)c < 32) o += ' '; else o += c; } return o;
}
std::string fmt(double v, int decimals)
{
    std::ostringstream ss; ss.setf(std::ios::fixed); ss.precision(decimals); ss << v; return ss.str();
}

